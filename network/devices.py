"""Device identity sync for INA v2.

One source of truth for "which device is which": the admin-owned
``policy/devices.yaml`` (name -> MAC -> class, optional fixed IP). The policy
engine already resolves names there; this module makes the router agree:

1. dnsmasq reservations. ``render_dhcp_hosts()`` writes ``/etc/ina/dhcp-hosts``
   (read by dnsmasq via ``dhcp-hostsfile=``, re-read on SIGHUP), so every
   registered MAC gets its admin-assigned name, and its fixed IP if one is
   set. Leases then carry 'guest-phone', not whatever hostname the phone
   chose for itself.
2. Anti-spoofing. Devices with a fixed IP are written to the ``managed_ips``
   and ``mac_ip_bind`` sets of ``inet ina_filter``. The prerouting rule then
   drops a reserved IP arriving from any other MAC.
3. Fallback resolution. ``device_mac(name)`` lets the service find a
   registered device by MAC when its current lease still shows another
   hostname (e.g. before its first renewal after a sync).

Run with: ``sudo ina-netctl sync-devices`` (and automatically from reconcile).
"""

from __future__ import annotations

import functools
import ipaddress
import os
import tempfile
from typing import Any, Callable, Dict, List, Optional, Tuple

CommandRunner = Callable[[List[str], float], Tuple[int, str, str]]

DHCP_HOSTS_FILE = "/etc/ina/dhcp-hosts"
ROUTER_IP = "192.168.50.1"
MANAGED_SUBNET = ipaddress.IPv4Network("192.168.50.0/24")
# The MACs shipped in devices.yaml; a sync with these would bind nothing real.
PLACEHOLDER_MAC_PREFIX = "aa:bb:cc:dd:ee:"


def _default_runner(args: List[str], timeout: float = 5.0) -> Tuple[int, str, str]:
    from inav2.network.device_discovery import default_command_runner
    return default_command_runner(args, timeout)


def dhcp_hosts_file() -> str:
    return os.environ.get("INA_DHCP_HOSTS_FILE") or DHCP_HOSTS_FILE


def load_devices(policy_dir: Optional[str] = None) -> List[Any]:
    """Registered devices from policy/devices.yaml (validated by the policy loader)."""
    from inav2.policy.engine import PolicyEngine

    return PolicyEngine.from_files(policy_dir).registry.devices()


@functools.lru_cache(maxsize=1)
def _mac_by_name() -> Dict[str, str]:
    try:
        return {d.name: d.mac for d in load_devices() if d.mac}
    except Exception:  # noqa: BLE001 - resolution falls back to leases only
        return {}


def device_mac(name: str) -> Optional[str]:
    """MAC registered for a device name in devices.yaml, if any."""
    return _mac_by_name().get(name.strip().lower())


def _reservable(devices: List[Any]) -> List[Any]:
    """Devices that get a DHCP reservation: everything with a MAC except the router itself."""
    return [d for d in devices if d.mac and d.ip != ROUTER_IP]


def placeholder_devices(devices: List[Any]) -> List[str]:
    return [d.name for d in devices if (d.mac or "").lower().startswith(PLACEHOLDER_MAC_PREFIX)]


def render_dhcp_hosts(devices: List[Any]) -> str:
    """dnsmasq dhcp-hostsfile content: 'mac,ip,name' (fixed IP) or 'mac,name'."""
    lines = [
        "# Generated by 'ina-netctl sync-devices' from policy/devices.yaml. Do not edit by hand.",
        "# Format (dnsmasq dhcp-hostsfile): <mac>,[<ip>,]<name>",
    ]
    for d in _reservable(devices):
        if d.ip:
            ip = ipaddress.IPv4Address(d.ip)
            if ip not in MANAGED_SUBNET or ip in (MANAGED_SUBNET.network_address,
                                                  MANAGED_SUBNET.broadcast_address):
                raise ValueError(f"devices.yaml: {d.name} has IP {d.ip} outside {MANAGED_SUBNET}.")
            lines.append(f"{d.mac},{d.ip},{d.name}")
        else:
            lines.append(f"{d.mac},{d.name}")
    return "\n".join(lines) + "\n"


def write_dhcp_hosts(content: str, path: Optional[str] = None) -> str:
    """Atomically replace the dnsmasq hosts file. Returns the path written."""
    path = path or dhcp_hosts_file()
    dir_name = os.path.dirname(path)
    os.makedirs(dir_name, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=dir_name, delete=False, encoding="utf-8") as tf:
        tf.write(content)
        tf.flush()
        os.fsync(tf.fileno())
        temp_name = tf.name
    os.chmod(temp_name, 0o644)
    os.replace(temp_name, path)
    return path


def antispoof_transaction(devices: List[Any]) -> str:
    """One nft transaction replacing the anti-spoofing sets with the fixed-IP devices."""
    fixed = [d for d in _reservable(devices) if d.ip]
    lines = [
        "flush set inet ina_filter managed_ips",
        "flush set inet ina_filter mac_ip_bind",
    ]
    if fixed:
        lines.append("add element inet ina_filter managed_ips { "
                     + ", ".join(d.ip for d in fixed) + " }")
        lines.append("add element inet ina_filter mac_ip_bind { "
                     + ", ".join(f"{d.mac} . {d.ip}" for d in fixed) + " }")
    return "\n".join(lines) + "\n"


def sync_antispoof_sets(devices: List[Any], runner: Optional[CommandRunner] = None) -> int:
    """Apply antispoof_transaction() atomically. Returns the number of bound devices."""
    run = runner or _default_runner
    with tempfile.NamedTemporaryFile("w", suffix=".nft", delete=False, encoding="utf-8") as tf:
        tf.write(antispoof_transaction(devices))
        temp_name = tf.name
    try:
        code, stdout, stderr = run(["nft", "-f", temp_name], 10.0)
    finally:
        os.unlink(temp_name)
    if code != 0:
        raise RuntimeError(f"Could not update anti-spoofing sets: {(stderr or stdout).strip()}")
    return len([d for d in _reservable(devices) if d.ip])


def reload_dnsmasq(runner: Optional[CommandRunner] = None) -> bool:
    """SIGHUP dnsmasq so it re-reads dhcp-hostsfile (no restart, leases kept)."""
    run = runner or _default_runner
    code, _, _ = run(["systemctl", "kill", "--signal=HUP", "dnsmasq.service"], 10.0)
    return code == 0


def sync_devices(
    runner: Optional[CommandRunner] = None,
    policy_dir: Optional[str] = None,
    hosts_path: Optional[str] = None,
    allow_placeholders: bool = False,
    reload: bool = True,
) -> Dict[str, Any]:
    """Write dnsmasq reservations and anti-spoofing sets from devices.yaml."""
    from inav2.network.access_control import ensure_ina_filter_table

    devices = load_devices(policy_dir)
    placeholders = placeholder_devices(devices)
    if placeholders and not allow_placeholders:
        raise ValueError(
            "policy/devices.yaml still has the example MACs (aa:bb:cc:dd:ee:..) for: "
            + ", ".join(placeholders)
            + ". Replace them with the real devices' MACs, or pass --allow-placeholders."
        )
    path = write_dhcp_hosts(render_dhcp_hosts(devices), hosts_path)
    ensure_ina_filter_table(runner)
    bound = sync_antispoof_sets(devices, runner)
    reloaded = reload_dnsmasq(runner) if reload else False
    _mac_by_name.cache_clear()
    return {
        "reservations": len(_reservable(devices)),
        "anti_spoofing_bound": bound,
        "dhcp_hosts_file": path,
        "dnsmasq_reloaded": reloaded,
    }
